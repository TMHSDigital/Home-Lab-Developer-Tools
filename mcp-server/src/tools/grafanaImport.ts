import { z } from "zod";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { execSSH } from "../utils/ssh-api.js";
import { completeJson } from "../utils/json-output.js";
import { nodeParam } from "../utils/node-param.js";
import { confirmParam, confirmCancelled } from "../utils/confirm-param.js";
import { destructive } from "../utils/annotations.js";
import { SERVICES, servicePort, grafanaAuth, curlErrorResponse } from "../utils/service-http.js";

const SERVICE = SERVICES.grafana;
const MAX_JSON_BYTES = 1024 * 1024;
const folderSchema = z.string().max(40);
const dashboardSchema = z.object({
  title: z.string().refine((title) => title.trim().length > 0),
  uid: z.string().max(40).nullable().optional(),
}).passthrough();

/** Accept both a raw model and the envelope returned by grafanaSnapshot. */
function readDashboard(json: string) {
  if (Buffer.byteLength(json, "utf8") > MAX_JSON_BYTES) {
    throw new Error("dashboardJson exceeds the 1 MiB UTF-8 limit.");
  }
  let value: unknown;
  try {
    value = JSON.parse(json);
  } catch {
    throw new Error("dashboardJson must contain valid JSON.");
  }
  const envelope = z.object({ dashboard: z.record(z.string(), z.unknown()), meta: z.unknown().optional() }).safeParse(value);
  const parsed = dashboardSchema.safeParse(envelope.success ? envelope.data.dashboard : value);
  if (!parsed.success) {
    throw new Error("dashboardJson must contain a dashboard object with a non-empty title and an optional UID of at most 40 characters.");
  }
  let folderUid: string | undefined;
  if (envelope.success && envelope.data.meta !== undefined) {
    const meta = z.object({ folderUid: folderSchema.optional() }).safeParse(envelope.data.meta);
    if (!meta.success) throw new Error("Export metadata must be an object with an optional folderUid of at most 40 characters.");
    folderUid = meta.data.folderUid;
  }
  return { dashboard: parsed.data, folderUid };
}

const inputSchema = {
  ...nodeParam,
  dashboardJson: z.string().superRefine((value, ctx) => {
    try {
      readDashboard(value);
    } catch (error) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: (error as Error).message });
    }
  }).describe("Raw dashboard JSON or a grafanaSnapshot export; maximum 1 MiB of UTF-8 input"),
  folderUid: folderSchema.optional().describe("Destination folder UID; defaults to the exported folder, then root. An empty string selects root."),
  overwrite: z.boolean().default(false).describe("Replace an existing dashboard with the same UID or title in the destination folder"),
  ...confirmParam,
};

export function register(server: McpServer): void {
  server.registerTool(
    "homelab_grafanaImport",
    {
      description: "Import a Grafana dashboard and return its UID and URL (requires confirm=true)",
      inputSchema,
      // Without a UID, repeated imports can create distinct dashboards.
      annotations: destructive(false),
    },
    async (args) => {
      let port = SERVICE.defaultPort;
      let auth = "";
      const redact = (text: string) => auth ? text.split(auth).join(auth.startsWith("-H")
        ? "-H 'Authorization: Bearer ****'" : "-u '****'") : text;
      try {
        const { dashboard, folderUid: exportedFolder } = readDashboard(args.dashboardJson);
        const folderUid = args.folderUid ?? exportedFolder ?? "";
        const overwrite = args.overwrite ?? false;
        port = servicePort(SERVICE, args.node);
        auth = grafanaAuth(args.node);
        const command = `curl -sf ${auth} -X POST -H 'Content-Type: application/json' --data-binary @- 'http://localhost:${port}/api/dashboards/db'`;
        if (args.confirm !== true) {
          return confirmCancelled("Grafana dashboard import", {
            node: args.node,
            commands: () => [redact(command)],
            note: `Dashboard: ${JSON.stringify(dashboard.title)}; UID: ${dashboard.uid || "generated by Grafana"}; ` +
              `folder: ${folderUid || "root"}; overwrite: ${overwrite}. Dashboard JSON is sent via stdin.`,
          });
        }
        const payload = JSON.stringify({
          // Database-local IDs and versions must not bypass overwrite=false.
          dashboard: { ...dashboard, id: null, version: 0 },
          folderUid,
          overwrite,
        });
        const output = await execSSH(command, args.node, { stdin: payload });
        const result = z.object({ status: z.literal("success"), uid: z.string().min(1), url: z.string().min(1) })
          .safeParse(JSON.parse(completeJson(output)));
        if (!result.success) throw new Error("Grafana returned an unexpected import response; expected success, UID and URL. Check the dashboard in Grafana before retrying.");
        return { content: [{ type: "text" as const, text: `Dashboard imported.\nUID: ${result.data.uid}\nURL: ${result.data.url}` }] };
      } catch (error) {
        const response = curlErrorResponse(error, SERVICE, port, {
          httpError: `Grafana rejected the dashboard import. ${SERVICE.authHint} ` +
            "Check write permission, the destination folder and the dashboard model. An existing UID or title requires overwrite=true.",
        });
        return { ...response, content: response.content.map((item) => ({ ...item, text: redact(item.text) })) };
      }
    },
  );
}
